function getParentGroupId(productId: string): string {
  if (productId.startsWith("jacks-accessories")) return "jacks-accessories";
  const prefix = productId.split("-")[0];
  const map: Record<string, string> = {
    jacks: "jacks",
    cylinders: "jacks",
    pumps: "pumps",
    pullers: "pullers",
    presses: "presses",
    cutting: "cutting",
    threading: "threading",
    benders: "benders",
    rescue: "rescue",
    special: "special",
    riklin: "riklin",
  };
  return map[prefix] ?? "jacks";
}

